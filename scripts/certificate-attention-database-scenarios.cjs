const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
module.exports = async ({ db, event, vol, mo, other, asUser, one, rejects }) => {
  await asUser(mo);
  const organisation = (await one('select organisation_id from public.events where id=$1', [event])).organisation_id;
  const testEvent = (await one(`insert into public.events(organisation_id,name,venue_name,start_date,end_date,operating_start_time,operating_end_time,timezone,created_by)
    values($1,'Certificate test','Test venue',current_date+60,current_date+62,'09:00','18:00','UTC',$2) returning id,start_date::text,end_date::text`, [organisation, mo]));
  const cert = randomUUID(), file = `${vol}/${cert}/expiry.pdf`;
  await asUser(vol);
  await db.query("insert into storage.objects(bucket_id,name) values('certificates',$1)", [file]);
  await db.query("insert into public.certifications(id,user_id,title,storage_path,mime_type,size_bytes) values($1,$2,'First Aid',$3,'application/pdf',50)", [cert, vol, file]);
  const claimed = (await one('select public.claim_certificate_processing($1) as c', [cert])).c;
  const fields = { type: 'First Aid', holderName: 'vol', certificateNumber: null, issuer: 'Test', issuedAt: null, expiresAt: testEvent.start_date, confidence: .99 };
  await db.exec('reset role; set role service_role');
  await db.query('select public.finish_certificate_processing($1,$2,$3,null)', [cert, claimed.attempt, JSON.stringify(fields)]);
  await asUser(mo);
  const inbox = async () => (await one('select public.my_notifications() as n')).n.filter(n => n.event_id === testEvent.id && n.source_id === cert);
  assert.equal((await inbox()).length, 0, 'No alert for a volunteer who has not joined');
  await db.exec('reset role');
  await db.query("insert into public.event_memberships(event_id,user_id,event_role,status) values($1,$2,'volunteer','active')", [testEvent.id, vol]);
  await asUser(mo);
  assert.equal((await inbox()).filter(n => !n.read_at).length, 1, 'Joining flags existing certificate expiry');
  await asUser(vol);
  assert.equal((await inbox()).length, 0, 'Volunteer cannot read manager certificate alerts');
  const retry = (await one('select public.claim_certificate_processing($1) as c', [cert])).c;
  await asUser(mo);
  assert.equal((await inbox()).filter(n => !n.read_at).length, 1, 'Retrying extraction does not hide the existing date warning');
  await db.exec('reset role; set role service_role');
  await db.query('select public.finish_certificate_processing($1,$2,$3,null)', [cert, retry.attempt, JSON.stringify(fields)]);
  await asUser(mo);
  assert.equal((await inbox()).filter(n => !n.read_at).length, 1, 'Identical extraction retry does not duplicate warning');
  await asUser(other);
  assert.equal((await inbox()).length, 0, 'Unrelated coordinator cannot read alerts');
  await asUser(mo);
  await db.query('select public.review_certification($1,$2,false,true,$3)', [cert, JSON.stringify(fields), 'Reviewed the original; expiry during event.']);
  assert.equal((await inbox()).filter(n => !n.read_at).length, 1, 'Approval cannot waive expiry');
  await db.exec('reset role');
  await db.query('update public.events set start_date=start_date+1,end_date=end_date+1 where id=$1', [testEvent.id]);
  await asUser(mo);
  assert.match((await inbox()).find(n => !n.read_at).body, /before the event starts/);
  await db.exec('reset role');
  await db.query('update public.events set start_date=start_date-1,end_date=end_date-1 where id=$1', [testEvent.id]);
  await db.query('select public.refresh_event_certificate_attention($1)', [testEvent.id]);
  await db.query('select public.refresh_event_certificate_attention($1)', [testEvent.id]);
  await asUser(mo);
  assert.equal((await inbox()).filter(n => !n.read_at).length, 1, 'Recurring warning flags once; refreshes are deduplicated');
  // Resolve, then recreate the same issue: a new episode must draw attention.
  fields.expiresAt = testEvent.end_date;
  await db.query('select public.review_certification($1,$2,false,true,$3)', [cert, JSON.stringify(fields), 'Valid through the final event day.']);
  assert.equal((await inbox()).filter(n => !n.read_at).length, 0);
  fields.expiresAt = testEvent.start_date;
  await db.query('select public.review_certification($1,$2,false,true,$3)', [cert, JSON.stringify(fields), 'Corrected expiry from original.']);
  assert.equal((await inbox()).filter(n => !n.read_at).length, 1);
  await db.exec('reset role');
  await db.query("update public.event_memberships set status='inactive' where event_id=$1 and user_id=$2", [testEvent.id, vol]);
  await asUser(mo);
  assert.equal((await inbox()).filter(n => !n.read_at).length, 0, 'Removing volunteer clears active warning');
  assert.ok((await inbox()).length >= 4, 'Warning history retained');
  await rejects('select public.refresh_certificate_attention($1,$2)', [testEvent.id, cert], /permission denied/);
  console.log('Certificate attention: saved evidence on join, event-date changes, approval, recurrence, deduplication, resolution and role isolation passed.');
};
